/* Езици: всички текстове на приложението. Всеки запис е [български, английски, немски].
   В HTML: data-i18n (текст), data-i18n-html (текст с <b>/<a>), data-i18n-ph (placeholder), data-i18n-title (title + aria-label).
   В JS: tr('ключ', { променливи }). Нов език = нов елемент във всеки масив + запис в LANGS и IDX. */

const LANGS = { bg: 'Български', en: 'English', de: 'Deutsch' };
const IDX = { bg: 0, en: 1, de: 2 };

let LANG = (() => {
  try {
    const raw = localStorage.getItem('morebtc.settings');
    const s = raw ? JSON.parse(raw) : {};
    if (LANGS[s.lang]) return s.lang;
    // потребител отпреди езиците (има запазени данни) → остава на български
    if (raw || localStorage.getItem('morebtc.portfolio') || localStorage.getItem('morebtc.tab')) return 'bg';
  } catch { }
  const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || 'en').slice(0, 2).toLowerCase();
  return LANGS[nav] ? nav : 'en';
})();
const loc = () => ({ bg: 'bg-BG', en: 'en-US', de: 'de-DE' })[LANG];

function tr(key, vars) {
  const e = STR[key];
  if (!e) return key;
  let s = e[IDX[LANG]] ?? e[0];
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// пореден ден от месеца: 20-то / 20th / 20.
function ordDay(n) {
  n = +n;
  if (LANG === 'en') return n + ((n % 100 >= 11 && n % 100 <= 13) ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' }[n % 10] || 'th'));
  if (LANG === 'de') return n + '.';
  return `${n}-${(n % 100 >= 11 && n % 100 <= 19) ? 'то' : ({ 1: 'во', 2: 'ро', 7: 'мо', 8: 'мо' }[n % 10] || 'то')}`;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = tr(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = tr(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
}

